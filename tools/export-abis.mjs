// Copies the ABIs the website needs from Foundry's out/ into web/src/abi/*.ts as `as const` arrays,
// so wagmi/viem infer argument and return types. Run after `forge build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = [
  "Lodestar",
  "LodestarFactory",
  "Exile",
  "Sandfall",
  "AscendSwapper",
  "IAscendLaunchpad",
  "IListingDesk",
  "MockERC20",
];
const outDir = join(root, "web/src/abi");
mkdirSync(outDir, { recursive: true });

const index = [];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by tools/export-abis.mjs. Do not edit.\nexport const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${id} } from "./${name}";`);
}
writeFileSync(join(outDir, "index.ts"), index.join("\n") + "\n");
console.log(`exported ${contracts.length} ABIs to web/src/abi`);
